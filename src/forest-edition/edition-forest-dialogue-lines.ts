export function createForestDialogueDeck(random = Math.random) {
  let deck: number[] = []; let last = -1
  return () => {
    if (!deck.length) {
      deck = FOREST_DIALOGUE_LINES.map((_, i) => i)
      for (let i = deck.length - 1; i > 0; i--) {
        const j = Math.floor(random() * (i + 1)); [deck[i], deck[j]] = [deck[j], deck[i]]
      }
      if (deck[deck.length - 1] === last) [deck[0], deck[deck.length - 1]] = [deck[deck.length - 1], deck[0]]
    }
    last = deck.pop()!
    return FOREST_DIALOGUE_LINES[last]
  }
}
